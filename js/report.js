let reports = JSON.parse(sessionStorage.getItem("reports")) || [];

// Update stat cards from live sessionStorage data
function updateReportCards() {
    const resources     = JSON.parse(sessionStorage.getItem("resources"))     || [];
    const beneficiaries = JSON.parse(sessionStorage.getItem("beneficiaries")) || [];
    const distributions = JSON.parse(sessionStorage.getItem("distributions")) || [];

    document.getElementById("rpt-resources").textContent     = resources.length;
    document.getElementById("rpt-beneficiaries").textContent = beneficiaries.length;
    document.getElementById("rpt-distributions").textContent = distributions.length;
    document.getElementById("rpt-pending").textContent       =
        distributions.filter(d => d.status === "Pending").length;
}

function renderReports() {
    const tbody = document.getElementById("table-body");
    if (reports.length === 0) {
        tbody.innerHTML = `<tr><td colspan="5" style="text-align:center;color:#9ca3af;padding:30px;">No reports generated yet</td></tr>`;
        return;
    }
    tbody.innerHTML = reports.map((r, i) => `
        <tr>
            <td><strong>${r.name}</strong></td>
            <td>${r.type}</td>
            <td>${r.date}</td>
            <td>${r.generatedBy}</td>
            <td>
                <div style="display:flex;gap:8px;">
                    <button class="btn-edit" onclick="viewReport(${i})">
                        <i class="fa-solid fa-eye"></i> View
                    </button>
                    <button class="btn-danger" onclick="deleteReport(${i})">
                        <i class="fa-solid fa-trash"></i> Delete
                    </button>
                </div>
            </td>
        </tr>`).join("");
}

function addReport() {
    const type     = document.getElementById("selReportType").value;
    const dateFrom = document.getElementById("txtDateFrom").value;
    const dateTo   = document.getElementById("txtDateTo").value;

    if (!type || !dateFrom || !dateTo) {
        alert("Please fill all report fields."); return;
    }

    const reportName = type === "monthly" ? "Monthly Report" : "Resource Report";

    reports.push({
        name: reportName,
        type,
        date: new Date().toLocaleDateString(),
        generatedBy: "Staff",
        from: dateFrom,
        to: dateTo
    });

    sessionStorage.setItem("reports", JSON.stringify(reports));
    renderReports();

    document.getElementById("selReportType").value = "";
    document.getElementById("txtDateFrom").value   = "";
    document.getElementById("txtDateTo").value     = "";

    alert("Report generated successfully!");
}

function viewReport(index) {
    const r = reports[index];
    alert(
        "Report Name: "   + r.name        + "\n" +
        "Type: "          + r.type        + "\n" +
        "Date Generated: "+ r.date        + "\n" +
        "Generated By: "  + r.generatedBy + "\n" +
        "Date From: "     + r.from        + "\n" +
        "Date To: "       + r.to
    );
}

function deleteReport(index) {
    if (!confirm("Are you sure you want to delete this report?")) return;
    reports.splice(index, 1);
    sessionStorage.setItem("reports", JSON.stringify(reports));
    renderReports();
}

// Init
updateReportCards();
renderReports();